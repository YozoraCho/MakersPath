local ALL_WEIGHT_KEYS = {
  -- Primary
  "STRENGTH","AGILITY","STAMINA","INTELLECT","SPIRIT",

  -- Armor / defensive
  "ARMOR","DEFENSE_SKILL","DODGE","PARRY","BLOCK","BLOCK_VALUE",
  "FIRE_RESISTANCE","NATURE_RESISTANCE","FROST_RESISTANCE","SHADOW_RESISTANCE","ARCANE_RESISTANCE",

  -- Health / mana
  "HEALTH","MANA","HEALTH_REGENERATION","MANA_REGENERATION",

  -- Attack / weapon
  "ATTACK_POWER","MELEE_ATTACK_POWER","RANGED_ATTACK_POWER","FERAL_ATTACK_POWER",
  "DAMAGE_PER_SECOND",

  -- Ratings
  "CRIT","CRIT_SPELL","HIT","HIT_SPELL","HASTE","HASTE_SPELL",
  "EXPERTISE","ARMOR_PENETRATION","SPELL_PENETRATION",

  -- Spell / healing
  "SPELL_DAMAGE_DONE","SPELL_HEALING_DONE",
  "SPELL_DAMAGE_DONE_HOLY","SPELL_DAMAGE_DONE_FIRE","SPELL_DAMAGE_DONE_NATURE",
  "SPELL_DAMAGE_DONE_FROST","SPELL_DAMAGE_DONE_SHADOW","SPELL_DAMAGE_DONE_ARCANE",

  -- Misc / compatibility
  "RESILIENCE",
}

local function FillMissingWeightKeys(tbl)
  if type(tbl) ~= "table" then return end
  for _, key in ipairs(ALL_WEIGHT_KEYS) do
    if tbl[key] == nil then
      tbl[key] = 0.00
    end
  end
end

for _, classTbl in pairs(M) do
  if type(classTbl) == "table" then
    for _, specTbl in pairs(classTbl) do
      if type(specTbl) == "table" then
        FillMissingWeightKeys(specTbl)
      end
    end
  end
end

